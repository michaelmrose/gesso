(def application-build-version
  1)

(def ^:private application-build-option-keys
  #{:receipt-path
    :realization-options-var})

(defn- fully-qualified-symbol?
  [value]
  (and
   (symbol? value)
   (some? (namespace value))
   (seq (name value))))

(defn- require-realization-options-var!
  [manifest realization-options-var]
  (let [optimistic?
        (contains? (:features manifest) :optimistic)]
    (when (and optimistic?
               (nil? realization-options-var))
      (throw
       (build-error
        :missing-realization-options-var
        "BrowserAssemblyManifest enables optimism, so the application build requires one fully-qualified ClojureScript realization-options Var."
        {:manifest-name (:name manifest)
         :features (:features manifest)})))

    (when (and (some? realization-options-var)
               (not (fully-qualified-symbol?
                     realization-options-var)))
      (throw
       (build-error
        :invalid-realization-options-var
        "Application browser realization options must be named by one fully-qualified ClojureScript Var symbol."
        {:manifest-name (:name manifest)
         :realization-options-var realization-options-var})))

    realization-options-var))

(defn- generated-entrypoint-ns
  []
  (symbol
   (str
    "gesso.generated.browser.application_"
    (str/replace
     (str (UUID/randomUUID))
     "-"
     "_"))))

(defn- namespace-source-path
  [source-root ns-sym]
  (let [relative
        (-> (str ns-sym)
            (str/replace "." "/")
            (str/replace "-" "_"))]
    (io/file source-root (str relative ".cljs"))))

(defn- generated-namespace-symbol?
  [value]
  (and
   (symbol? value)
   (nil? (namespace value))
   (boolean
    (re-matches
     #"[A-Za-z_][A-Za-z0-9_.-]*"
     (name value)))))

(defn application-entrypoint-source
  "Return the generated ClojureScript source for one supported application
   browser entrypoint.

   manifest must be a current closed BrowserAssemblyManifest. The exact manifest
   value is embedded directly into the generated source and is therefore the same
   semantic value later used to stamp the generated JavaScript receipt.

   realization-options-var, when supplied, must be one fully-qualified CLJS Var
   symbol. Its namespace is required by the generated entrypoint and its value is
   passed only as the physical realization-options argument to bootstrap/init!.
   The application cannot override manifest-owned browser role, plan resolver,
   feature set, transport, or bootstrap identity through this generated source."
  [generated-ns manifest realization-options-var]
  (when-not (generated-namespace-symbol? generated-ns)
    (throw
     (build-error
      :invalid-generated-entrypoint-namespace
      "Generated application browser entrypoint requires one closed namespace symbol."
      {:generated-ns generated-ns})))

  (artifact/stamp manifest)
  (require-realization-options-var!
   manifest
   realization-options-var)

  (let [realization-ns
        (some-> realization-options-var namespace symbol)

        realization-local
        (some-> realization-options-var name symbol)]
    (str
     "(ns " generated-ns "\n"
     "  (:require\n"
     "   [gesso.live.browser.bootstrap :as bootstrap]"
     (when realization-ns
       (str "\n   [" realization-ns " :as application-realization]"))
     "))\n\n"
     "(def ^:private browser-assembly\n"
     "  '" (pr-str manifest) ")\n\n"
     "(defn ^:export init! []\n"
     "  (bootstrap/init!\n"
     "   browser-assembly"
     (when realization-local
       (str "\n   application-realization/" realization-local))
     "))\n\n"
     "(init!)\n")))

(defn- require-cljs-build-api!
  []
  (try
    (let [build
          (requiring-resolve 'cljs.build.api/build)

          inputs
          (requiring-resolve 'cljs.build.api/inputs)]
      (when-not (and build inputs)
        (throw
         (IllegalStateException.
          "cljs.build.api build functions did not resolve.")))
      {:build build
       :inputs inputs})
    (catch Throwable error
      (throw
       (build-error
        :clojurescript-compiler-unavailable
        "Supported application browser builds require ClojureScript on the JVM build classpath."
        {}
        error)))))

(defn- delete-tree-best-effort!
  [root]
  (let [root-file
        (io/file root)]
    (when (.exists root-file)
      (doseq [file (reverse (file-seq root-file))]
        (try
          (Files/deleteIfExists
           (.toPath file))
          (catch Throwable _
            nil))))))

(defn- emit-application-cljs!
  [manifest realization-options-var staged-artifact-path]
  (let [build-root
        (.toFile
         (Files/createTempDirectory
          "gesso-browser-application-"
          (make-array java.nio.file.attribute.FileAttribute 0)))

        source-root
        (io/file build-root "src")

        output-dir
        (io/file build-root "out")

        generated-ns
        (generated-entrypoint-ns)

        source-file
        (namespace-source-path
         source-root
         generated-ns)

        source
        (application-entrypoint-source
         generated-ns
         manifest
         realization-options-var)]
    (try
      (Files/createDirectories
       (.toPath (.getParentFile source-file))
       (make-array java.nio.file.attribute.FileAttribute 0))
      (spit source-file source :encoding "UTF-8")

      (let [{:keys [build inputs]}
            (require-cljs-build-api!)]
        (build
         (inputs (.getPath source-root))
         {:optimizations :advanced
          :output-dir (.getPath output-dir)
          :output-to (str staged-artifact-path)}))
      (finally
        (delete-tree-best-effort! build-root)))))

(defn build-application-artifact!
  "Build one application browser artifact through the ordinary Gesso-owned
   semantic + generated-source + physical publication path.

   declaration is the same application browser declaration accepted by
   gesso.live.browser.entrypoint/compile-browser-assembly!. Gesso resolves and
   preflights it exactly once into a BrowserAssemblyManifest. That exact manifest
   is then embedded into a generated ClojureScript bootstrap namespace and also
   supplied to build-generated-artifact! for the final receipt stamp.

   Options:

     :realization-options-var
       Optional fully-qualified CLJS Var symbol whose value contains only the
       physical realization options accepted by gesso.live.browser.bootstrap.
       It is required when the manifest enables optimism.

     :receipt-path
       Optional non-default ArtifactReceipt path.

   The ClojureScript compiler is loaded dynamically from the JVM build classpath
   and advanced-compiles the Gesso-generated wrapper. Application build code does
   not provide an emitter callback and therefore cannot accidentally stamp bytes
   produced from an unrelated semantic entrypoint while using this supported
   path.

   This correspondence remains relative to the trusted ClojureScript compiler
   implementation; it does not claim to prove the compiler itself. Returns the
   final verified ArtifactReceipt."
  ([declaration artifact-path]
   (build-application-artifact!
    declaration
    artifact-path
    {}))
  ([declaration artifact-path {:keys [receipt-path
                                      realization-options-var]
                               :as options}]
   (let [unknown-options
         (seq
          (remove
           application-build-option-keys
           (keys options)))]
     (when unknown-options
       (throw
        (build-error
         :unknown-application-build-options
         "Application browser build received unsupported options."
         {:unknown-keys (set unknown-options)
          :allowed-keys application-build-option-keys}))))

   (let [manifest
         (entrypoint/compile-browser-assembly!
          declaration)

         realization-options-var
         (require-realization-options-var!
          manifest
          realization-options-var)]
     (build-generated-artifact!
      manifest
      artifact-path
      (fn [staged-artifact-path]
        (emit-application-cljs!
         manifest
         realization-options-var
         staged-artifact-path))
      (cond-> {}
        receipt-path
        (assoc :receipt-path receipt-path))))))
