(defn- path-parent
  [^Path path]
  (or
   (.getParent path)
   (.toAbsolutePath
    (.getParent
     (.toAbsolutePath path)))))

(defn- move-replacing!
  [^Path source ^Path target]
  (try
    (Files/move
     source
     target
     (into-array
      java.nio.file.CopyOption
      [StandardCopyOption/ATOMIC_MOVE
       StandardCopyOption/REPLACE_EXISTING]))
    (catch AtomicMoveNotSupportedException _
      (Files/move
       source
       target
       (into-array
        java.nio.file.CopyOption
        [StandardCopyOption/REPLACE_EXISTING]))))
  target)

(defn- write-edn-atomically!
  [metadata-path value]
  (let [target
        (.toPath
         (io/file metadata-path))

        parent
        (path-parent target)

        temp
        (.resolve
         parent
         (str
          "."
          (.getFileName target)
          "."
          (UUID/randomUUID)
          ".tmp"))

        bytes
        (.getBytes
         (str (pr-str value) "\n")
         StandardCharsets/UTF_8)]
    (Files/createDirectories
     parent
     (make-array java.nio.file.attribute.FileAttribute 0))
    (try
      (Files/write
       temp
       bytes
       (make-array java.nio.file.OpenOption 0))
      (move-replacing! temp target)
      (finally
        (Files/deleteIfExists temp)))))

(defn- publish-artifact-receipt!
  [artifact-path metadata-path receipt]
  (try
    (write-edn-atomically!
     metadata-path
     receipt)
    (catch Throwable error
      (throw
       (build-error
        :artifact-receipt-publication-failed
        "Gesso could not publish the generated browser ArtifactReceipt; the artifact must not be consumed until a matching receipt is published."
        {:artifact-path (str artifact-path)
         :receipt-path (str metadata-path)
         :artifact (:artifact receipt)
         :stamp (:stamp receipt)}
        error)))))

(defn record-generated-artifact!
  "Record exact correspondence metadata for one successfully generated browser
   artifact.

   By default metadata is written beside the artifact at
   `<artifact>.gesso-artifact.edn`. Pass :receipt-path to place the receipt
   elsewhere when a build system has an explicit metadata directory.

   The JavaScript artifact must already exist and be non-empty. The receipt is
   written only after its semantic stamp and byte identity have both been
   derived successfully. Returns the receipt."
  ([manifest artifact-path]
   (record-generated-artifact!
    manifest
    artifact-path
    {}))
  ([manifest artifact-path {:keys [receipt-path]
                            :as options}]
   (let [unknown-options
         (seq
          (remove
           #{:receipt-path}
           (keys options)))]
     (when unknown-options
       (throw
        (build-error
         :unknown-record-options
         "Generated browser artifact recording received unsupported options."
         {:unknown-keys (set unknown-options)
          :allowed-keys #{:receipt-path}}))))
   (let [receipt
         (artifact-receipt
          manifest
          artifact-path)

         metadata-path
         (or receipt-path
             (gesso.live.browser.build/receipt-path
              artifact-path))]
     (publish-artifact-receipt!
      artifact-path
      metadata-path
      receipt)
     receipt)))

(def ^:private edn-eof
  (Object.))

(defn- read-one-edn-form
  [text]
  (with-open [reader
              (PushbackReader.
               (StringReader. text))]
    (let [value
          (edn/read
           {:eof edn-eof}
           reader)]
      (when
       (identical? edn-eof value)
        (throw
         (IllegalArgumentException.
          "Artifact receipt contains no EDN form.")))
      (let [trailing
            (edn/read
             {:eof edn-eof}
             reader)]
        (when-not
         (identical? edn-eof trailing)
          (throw
           (IllegalArgumentException.
            "Artifact receipt contains more than one EDN form."))))
      value)))

(defn read-artifact-receipt!
  "Read and recognize exactly one generated browser ArtifactReceipt from disk.

   Missing, unreadable, non-EDN, multi-form, or structurally invalid metadata
   fails closed. Whitespace and comments after the one receipt form are allowed,
   but a second EDN value is never silently ignored."
  [metadata-path]
  (let [file
        (io/file metadata-path)]
    (when-not (.isFile file)
      (throw
       (build-error
        :missing-artifact-receipt
        "Generated Gesso browser artifact receipt is missing."
        {:receipt-path (str metadata-path)})))
    (let [value
          (try
            (read-one-edn-form
             (slurp file :encoding "UTF-8"))
            (catch Throwable error
              (throw
               (build-error
                :unreadable-artifact-receipt
                "Generated Gesso browser artifact receipt must contain exactly one readable EDN value."
                {:receipt-path (str metadata-path)}
                error))))]
      (when-not
       (receipt? value)
        (throw
         (build-error
          :invalid-artifact-receipt
          "Generated Gesso browser artifact receipt has an invalid or unsupported shape."
          {:receipt-path (str metadata-path)
           :receipt value})))
      value)))

